# Builds WalkLevel: the interface, the exe (release, static C++ runtime), the language packs and
# the Inno Setup installer.
#   powershell -ExecutionPolicy Bypass -File packaging\build.ps1 -Version 0.6.0
# Output: dist-installer\WalkLevel-Setup-<version>.exe + .sha256 (named Bieznia-Setup up to 0.6.3).
# The release workflow signs it afterwards (docs/release-signing.md).
# Keep this file ASCII: Windows PowerShell 5.1 reads a .ps1 without a BOM as ANSI.
param(
    [Parameter(Mandatory = $true)][string]$Version,
    [string]$Iscc = ""
)
$ErrorActionPreference = 'Stop'
$root = Split-Path -Parent $PSScriptRoot            # repository root
Set-Location $root

if ($Version -notmatch '^\d+\.\d+\.\d+$') { throw "The version must look like 1.2.3" }

# 1. interface (dist/), built into the exe by Tauri
npm run check; if ($LASTEXITCODE) { throw "npm run check" }
npm run build; if ($LASTEXITCODE) { throw "npm run build" }

# 2. exe: its own build folder, C++ runtime linked statically (no vcruntime140.dll)
$env:CARGO_TARGET_DIR = Join-Path $root 'target-release'
$env:RUSTFLAGS = '-C target-feature=+crt-static'
# custom-protocol: the interface from dist/ is built into the exe (without it the exe looks for
# the Vite dev server and the window never shows) - the same thing `tauri build` turns on
cargo build --release -p walklevel --locked --features tauri/custom-protocol; if ($LASTEXITCODE) { throw "cargo build" }
Remove-Item Env:RUSTFLAGS

# 3. language packs (docs/i18n.md): every locales\<tag>\ listed in locales\languages.json, except
#    the built-in language, goes to target-installer\locales\<tag>\. installer.iss includes the
#    generated target-installer\languages.iss: one component per pack, installed into
#    {app}\locales\<tag>\. A new language needs no change here or in installer.iss.
$stage = Join-Path $root 'target-installer'
if (Test-Path $stage) { Remove-Item -Recurse -Force $stage }
New-Item -ItemType Directory -Force (Join-Path $stage 'locales') | Out-Null
$manifest = Get-Content -Raw -Encoding UTF8 (Join-Path $root 'locales\languages.json') | ConvertFrom-Json
$components = @()
$files = @()
$deletes = @()
$names = @()
foreach ($language in $manifest.languages) {
    $code = $language.code
    if ($code -eq $manifest.fallback) { continue }   # built into the exe
    if ($code -notmatch '^[A-Za-z0-9]{1,8}(-[A-Za-z0-9]{1,8})*$') { throw "Wrong language code: $code" }
    $source = Join-Path $root "locales\$code"
    $packFiles = @(Get-ChildItem -Path $source -Filter '*.json' -File -ErrorAction SilentlyContinue)
    if ($packFiles.Count -eq 0) { "Language $code has no pack in locales\$code, skipped"; continue }
    $target = Join-Path $stage "locales\$code"
    New-Item -ItemType Directory -Force $target | Out-Null
    $packFiles | Copy-Item -Destination $target
    # Inno component names: letters, digits and underscores (pt-BR -> pt_BR)
    $component = $code.Replace('-', '_')
    $description = $language.name.Replace('"', '""').Replace('{', '{{')
    $components += "Name: ""$component""; Description: ""$description""; Flags: disablenouninstallwarning"
    $files += "Source: ""..\target-installer\locales\$code\*.json""; DestDir: ""{app}\locales\$code""; Components: $component; Flags: ignoreversion"
    # always removed first, so a pack unchecked in a later installation is gone and a selected
    # one has no files left from an older version
    $deletes += "Type: filesandordirs; Name: ""{app}\locales\$code"""
    $names += $component
}
$include = @(
    '; Generated by packaging/build.ps1 from locales/languages.json. Do not edit.'
    "#define LanguagePacks "",$($names -join ','),"""
    '[Components]'
) + $components + @('[Files]') + $files + @('[InstallDelete]') + $deletes
[IO.File]::WriteAllLines((Join-Path $stage 'languages.iss'), [string[]]$include, (New-Object Text.UTF8Encoding $false))
"Language packs for the installer: $($names -join ', ')"

# 4. installer
if (-not $Iscc) { $Iscc = Join-Path $root 'tools\inno\ISCC.exe' }
if (-not (Test-Path $Iscc)) { throw "Inno Setup not found: $Iscc" }
& $Iscc "/DAppVersion=$Version" (Join-Path $PSScriptRoot 'installer.iss'); if ($LASTEXITCODE) { throw "ISCC" }

$setup = Join-Path $root "dist-installer\WalkLevel-Setup-$Version.exe"
$hash = (Get-FileHash $setup -Algorithm SHA256).Hash.ToLower()
"$hash  WalkLevel-Setup-$Version.exe" | Out-File -Encoding ascii "$setup.sha256"
$mb = [math]::Round((Get-Item $setup).Length / 1MB, 1)
$exe = [math]::Round((Get-Item (Join-Path $root 'target-release\release\walklevel.exe')).Length / 1MB, 1)
"Done: $setup ($mb MB, exe $exe MB), SHA-256 $hash"
